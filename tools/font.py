"""font.py: the 6 px English font (fonts/en6.txt) -> glyph bytes for tools/asm/text.asm, and tbl/en.tbl.

Glyph data: codes 10-7F, 16 bytes each (rows 0-11, bit 7 = column 0; rows 12-15 zero). en.tbl = the control codes
of tbl/jp.tbl + one line per glyph; build.py encodes the English with it.

    python -X utf8 tools/font.py        rewrite tbl/en.tbl and print a preview
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "fonts" / "en6.txt"
TBL = ROOT / "tbl" / "en.tbl"
FIRST, LAST = 0x10, 0x7F  # half-width range after the dispatch patch (tools/asm/text.asm)


def glyphs():
    """{code: (char, [12 row bytes])}"""
    out = {}
    for n, line in enumerate(SRC.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        code, ch, top, *rows = line.split("\t")
        rows = rows[0].split() if rows else []
        code, top = int(code, 16), int(top)
        bits = [0] * 12
        for r, row in enumerate(rows):
            assert len(row) == 5 and set(row) <= {".", "#"}, f"en6.txt:{n}: row {row!r} must be 5 of . or #"
            assert top + r < 12, f"en6.txt:{n}: past row 11"
            bits[top + r] = int(row.replace("#", "1").replace(".", "0"), 2) << 3
        assert FIRST <= code <= LAST and code not in out, f"en6.txt:{n}: bad or repeated code {code:02X}"
        out[code] = (ch, bits)
    return out


def data():
    g = glyphs()
    return b"".join(bytes(g[c][1] + [0] * 4) if c in g else bytes(16) for c in range(FIRST, LAST + 1))


def table_lines():
    ctrl = [l for l in (ROOT / "tbl" / "jp.tbl").read_text(encoding="utf-8").splitlines() if "={" in l]
    return ctrl + [f"{c:02X}={ch}" for c, (ch, _) in sorted(glyphs().items())]


def main():
    TBL.write_text("# English table: generated by tools/font.py from fonts/en6.txt; don't edit.\n"
                   + "\n".join(table_lines()) + "\n", encoding="utf-8")
    g = glyphs()
    for r in range(12):
        print("".join(format(g[c][1][r] >> 2, "06b").replace("0", ".").replace("1", "#")
                      for c in sorted(g) if 0x45 <= c <= 0x5E))
    print(f"{TBL}: {len(g)} glyphs")


if __name__ == "__main__":
    sys.exit(main())
