"""font.py: the English fonts -> glyph bytes, and tbl/en.tbl.

  - fonts/en6.txt: 6 px glyphs for the 12 px text engine; data() = codes 10-7F, 16 bytes each (rows 0-11,
    bit 7 = column 0; rows 12-15 zero), included by tools/asm/text.asm.
  - fonts/en8.txt: 8x8 menu glyphs; menu_font(raw) puts them into the decompressed CBC255 font (2bpp, tile =
    code - $10, ink colour 3 on colour 2), one column in from the left like the game's capitals.
en.tbl = the control codes of tbl/jp.tbl + one line per en6 glyph; build.py encodes the English with it.

    python -X utf8 tools/font.py        rewrite tbl/en.tbl and print a preview
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EN6, EN8 = ROOT / "fonts" / "en6.txt", ROOT / "fonts" / "en8.txt"
TBL = ROOT / "tbl" / "en.tbl"
FIRST, LAST = 0x10, 0x7F  # half-width range after the dispatch patch (tools/asm/text.asm)


def glyphs(src=EN6, height=12):
    """{code: (char, [row bytes, glyph columns 0-4 in bits 7-3])}"""
    out = {}
    for n, line in enumerate(src.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        code, ch, top, *rows = line.split("\t")
        rows = rows[0].split() if rows else []
        code, top = int(code, 16), int(top)
        bits = [0] * height
        for r, row in enumerate(rows):
            assert len(row) == 5 and set(row) <= {".", "#"}, f"{src.name}:{n}: row {row!r} must be 5 of . or #"
            assert top + r < height, f"{src.name}:{n}: past row {height - 1}"
            bits[top + r] = int(row.replace("#", "1").replace(".", "0"), 2) << 3
        assert FIRST <= code <= LAST and code not in out, f"{src.name}:{n}: bad or repeated code {code:02X}"
        out[code] = (ch, bits)
    return out


def data():
    g = glyphs()
    return b"".join(bytes(g[c][1] + [0] * 4) if c in g else bytes(16) for c in range(FIRST, LAST + 1))


def menu_font(raw):
    """The decompressed CBC255 menu font with the en8 glyphs drawn over their tiles."""
    raw = bytearray(raw)
    six = glyphs()
    for code, (ch, rows) in glyphs(EN8, 8).items():
        assert six.get(code, ("",))[0] == ch, f"en8.txt: {code:02X}={ch} but en6.txt has {six.get(code)}"
        t = (code - 0x10) * 16
        raw[t:t + 16] = b"".join(bytes([r >> 1, 0xFF]) for r in rows)
    return bytes(raw)


def table_lines():
    ctrl = [l for l in (ROOT / "tbl" / "jp.tbl").read_text(encoding="utf-8").splitlines() if "={" in l]
    return ctrl + [f"{c:02X}={ch}" for c, (ch, _) in sorted(glyphs().items())]


def main():
    TBL.write_text("# English table: generated by tools/font.py from fonts/en6.txt; don't edit.\n"
                   + "\n".join(table_lines()) + "\n", encoding="utf-8")
    for src, h in ((EN6, 12), (EN8, 8)):
        g = glyphs(src, h)
        for r in range(h):
            print("".join(format(g[c][1][r] >> 2, "06b").replace("0", ".").replace("1", "#")
                          for c in sorted(g) if 0x50 <= c <= 0x69))
    print(f"{TBL}: {len(glyphs())} glyphs")


if __name__ == "__main__":
    sys.exit(main())
