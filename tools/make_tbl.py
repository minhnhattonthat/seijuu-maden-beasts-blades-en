"""make_tbl.py: write tbl/jp.tbl from the font reading (work/font/match.tsv, or tbl/font_fixes.tsv overrides),
the half-width font and the control codes in docs/re/text.md.

    python -X utf8 tools/fontmatch.py && python -X utf8 tools/make_tbl.py

A glyph that reads as a character already taken gets the value ‹c› so decode/encode stays byte-exact; the
reviewer pass resolves those.
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MATCH = ROOT / "work" / "font" / "match.tsv"
FIXES = ROOT / "tbl" / "font_fixes.tsv"   # code<TAB>char, reviewed readings that beat the matcher
LAST_GLYPH = 0xFB9B                        # ♪ 　 （ ） end the font; cells after it are blank or garbage

HALF = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ!?…、。・:+-×/=「」『』"   # codes $10-$44, 6 px wide
CTRL = """\
00={end}
01={c01:1}
02={wait}
03={delay:1}
04={var:1}
05={c05}
06={c06}
07={c07}
08={sfx:1}
09={c09}
0A={clear}
0B={c0B}
0C={c0C}
0D={nl}
0E={choice:2}
0FFF={call:3}
0FFE={icall:3}
0F={num:4}
"""


def main():
    rows = list(csv.DictReader(MATCH.open(encoding="utf-8"), delimiter="\t"))
    fixes = {}
    if FIXES.exists():
        for line in FIXES.read_text(encoding="utf-8").splitlines():
            if line and not line.startswith("#"):
                code, ch = line.split("\t")[:2]
                fixes[code] = ch
    out = ["# Seijuu Maden: Beasts & Blades - Japanese table. Generated by tools/make_tbl.py; edit tbl/font_fixes.tsv.",
           "# Control codes (arg bytes after ':'): docs/re/text.md", CTRL.rstrip("\n")]
    seen = set()
    for i, ch in enumerate(HALF):
        out.append(f"{0x10 + i:02X}={ch if ch != ' ' else chr(92) + 's'}")
        seen.add(ch)
    dupes = 0
    for r in rows:
        code = r["code"]
        if int(code, 16) > LAST_GLYPH and len(code) == 4:
            break
        ch = fixes.get(code, r["char"])
        if not ch:
            continue
        if ch in seen:
            ch, dupes = f"‹{ch}›", dupes + 1
        seen.add(ch)
        out.append(f"{code}={ch}")
    (ROOT / "tbl").mkdir(exist_ok=True)
    (ROOT / "tbl" / "jp.tbl").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"tbl/jp.tbl: {len(out) - 3} entries, {dupes} duplicate readings marked ‹›")


if __name__ == "__main__":
    main()
